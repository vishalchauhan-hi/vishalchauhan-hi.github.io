#!/usr/bin/env node
// build-blog.mjs — turn the posts you write in blog/*.md into web pages.
// Plain Node, no dependencies.
//
//   node scripts/build-blog.mjs           build every post + the Blog list
//   node scripts/build-blog.mjs --check   only check everything is built (used by Site checks)
//
// You write:   blog/my-post.md            (see blog/_template.md)
// It makes:    blog-my-post.html          one page per post, in the site's style
//              blog.html                  the list of posts, newest first
// Files starting with "_" (like _template.md or _draft-…md) are never published.
// The .html files are generated: always edit the .md file, never the .html.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const check = process.argv.includes('--check');
const page = readFileSync('blog/_page.html', 'utf8').replace(/^<!--.*-->\n/, '');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const nice = (d) => { const [y, m] = d.split('-'); return `${MONTHS[+m - 1]} ${y}`; };
const GENERATED = (src) => `<!-- Generated by scripts/build-blog.mjs from ${src}. Edit that file, not this one. -->\n`;

/* ---------- a small Markdown reader (only what posts need) ---------- */
function inline(s) {
  return esc(s)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>')
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (m, t, u) => `<a href="${u.replace(/&amp;/g, '&')}">${t}</a>`);
}
function figure(alt, src) {
  return `<figure class="post-fig"><img loading="lazy" decoding="async" src="${src}" alt="${esc(alt)}" />` +
         (alt ? `<figcaption>${inline(alt)}</figcaption>` : '') + `</figure>`;
}
function markdown(md) {
  const out = [], lines = md.replace(/\r/g, '').split('\n');
  let para = [], list = null, quote = [];
  const flush = () => {
    if (para.length) { out.push(`<p>${inline(para.join(' '))}</p>`); para = []; }
    if (list) { out.push(`<${list.tag}>${list.items.map((i) => `<li>${inline(i)}</li>`).join('')}</${list.tag}>`); list = null; }
    if (quote.length) { out.push(`<blockquote><p>${inline(quote.join(' '))}</p></blockquote>`); quote = []; }
  };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i], t = line.trim();
    if (t.startsWith('```')) {                                     // code block
      flush(); const code = [];
      while (++i < lines.length && !lines[i].trim().startsWith('```')) code.push(lines[i]);
      out.push(`<pre class="code"><code>${esc(code.join('\n'))}</code></pre>`); continue;
    }
    if (t.startsWith('<')) {                                       // raw HTML block (until a blank line)
      flush(); const html = [line];
      while (i + 1 < lines.length && lines[i + 1].trim() !== '') html.push(lines[++i]);
      out.push(html.join('\n')); continue;
    }
    const img = t.match(/^!\[([^\]]*)\]\(([^)\s]+)\)$/);
    if (img) {                                                     // picture(s): one per line, side by side if consecutive
      flush(); const figs = [figure(img[1], img[2])];
      while (i + 1 < lines.length) {
        const nx = lines[i + 1].trim().match(/^!\[([^\]]*)\]\(([^)\s]+)\)$/);
        if (!nx) break; figs.push(figure(nx[1], nx[2])); i++;
      }
      out.push(figs.length > 1 ? `<div class="post-row-figs">${figs.join('')}</div>` : figs[0]); continue;
    }
    let m;
    if (!t) { flush(); continue; }
    if ((m = t.match(/^(#{2,3})\s+(.*)$/))) { flush(); out.push(`<h${m[1].length}>${inline(m[2])}</h${m[1].length}>`); continue; }
    if ((m = t.match(/^>\s?(.*)$/))) { if (para.length || list) flush(); quote.push(m[1]); continue; }
    if ((m = t.match(/^[-*]\s+(.*)$/)) || (m = t.match(/^\d+\.\s+(.*)$/))) {
      const tag = /^\d/.test(t) ? 'ol' : 'ul';
      if (para.length || quote.length || (list && list.tag !== tag)) flush();
      list = list || { tag, items: [] }; list.items.push(m[1]); continue;
    }
    if (list || quote.length) flush();
    para.push(t);
  }
  flush();
  return out.join('\n');
}

/* ---------- read posts ---------- */
function frontMatter(src, file) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) throw new Error(`${file}: missing the --- header (title, date, summary)`);
  const meta = {};
  for (const l of m[1].split('\n')) { const k = l.match(/^(\w+):\s*(.*)$/); if (k) meta[k[1]] = k[2].trim(); }
  for (const need of ['title', 'date', 'summary']) if (!meta[need]) throw new Error(`${file}: add "${need}:" to the header`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) throw new Error(`${file}: date must look like 2026-11-23`);
  return { meta, body: src.slice(m[0].length) };
}
const posts = readdirSync('blog').filter((f) => f.endsWith('.md') && !f.startsWith('_')).map((f) => {
  const { meta, body } = frontMatter(readFileSync(`blog/${f}`, 'utf8'), f);
  const slug = f.replace(/\.md$/, '');
  const words = body.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
  return { ...meta, slug, src: `blog/${f}`, file: `blog-${slug}.html`, body, minutes: Math.max(1, Math.round(words / 200)) };
}).sort((a, b) => b.date.localeCompare(a.date));

function render(file, title, description, image, content, src) {
  return GENERATED(src) + page
    .replaceAll('{{title}}', esc(title)).replaceAll('{{description}}', esc(description))
    .replaceAll('{{file}}', file).replaceAll('{{image}}', image || 'photo.jpg').replace('{{content}}', content);
}

const outputs = {};
for (const p of posts) {
  const cover = p.cover ? `        <figure class="post-cover"><img src="${p.cover}" alt="${esc(p.cover_alt || p.title)}" /></figure>\n` : '';
  outputs[p.file] = render(p.file, `${p.title} — Vishal Chauhan`, p.summary, p.cover, `    <article class="post">
      <div class="container post-wrap">
        <p class="section-eyebrow"><a href="blog.html">Blog</a> · ${nice(p.date)} · ${p.minutes} min read</p>
        <h1 class="page-title">${inline(p.title)}</h1>
${cover}${markdown(p.body)}
        <p class="post-back"><a href="blog.html">← All notes</a></p>
      </div>
    </article>
`, p.src);
}

const rows = posts.map((p) => `          <li class="post-row">
            <p class="post-date">${nice(p.date)}<br><span>${p.minutes} min read</span></p>
            <div>
${p.cover ? `              <a href="${p.file}"><img class="post-row-thumb" loading="lazy" src="${p.cover}" alt="" /></a>\n` : ''}              <h2><a href="${p.file}">${inline(p.title)}</a></h2>
              <p class="post-sum">${inline(p.summary)}</p>
${p.tags ? `              <p class="post-tags">${esc(p.tags).replace(/,\s*/g, ' · ')}</p>\n` : ''}            </div>
          </li>`).join('\n');
const intro = existsSync('blog/_intro.html') ? readFileSync('blog/_intro.html', 'utf8') : '';
outputs['blog.html'] = render('blog.html', 'Blog — Vishal Chauhan', 'Notes on research, prototyping and working with AI — Vishal Chauhan.', 'photo.jpg', `    <section>
      <div class="container">
        <p class="section-eyebrow">Blog</p>
        <h1 class="page-title">Notes.</h1>
${intro}        <ol class="post-list">
${rows || '          <li class="post-row"><p class="post-date"></p><div><p class="post-sum">No posts yet.</p></div></li>'}
        </ol>
      </div>
    </section>
`, 'blog/*.md');

/* ---------- write or check ---------- */
const stale = Object.entries(outputs).filter(([f, html]) => !existsSync(f) || readFileSync(f, 'utf8') !== html).map(([f]) => f);
const orphans = readdirSync('.').filter((f) => /^blog-.+\.html$/.test(f) && !outputs[f]);
if (check) {
  if (stale.length || orphans.length) {
    for (const f of stale) console.log(`✗ ${f} is out of date with its .md file. Run: node scripts/build-blog.mjs`);
    for (const f of orphans) console.log(`✗ ${f} has no blog/*.md source any more. Delete it, or restore its .md file.`);
    process.exit(1);
  }
  console.log(`✓ Blog is up to date (${posts.length} post${posts.length === 1 ? '' : 's'}).`);
} else {
  for (const f of stale) writeFileSync(f, outputs[f]);
  console.log(stale.length ? `✓ Built: ${stale.join(', ')}` : '✓ Blog already up to date.');
  if (orphans.length) console.log(`  Note: ${orphans.join(', ')} no longer has a .md file. Delete it if the post is gone.`);
}
