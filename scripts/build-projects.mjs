#!/usr/bin/env node
// build-projects.mjs — make the Projects list and one page per project.
// Plain Node, no dependencies.
//
//   node scripts/build-projects.mjs           build projects.html + project-<slug>.html
//   node scripts/build-projects.mjs --check   only check everything is built (used by Site checks)
//
// You edit:   projects/projects.json     one entry per project (title, years, tags, facts, papers)
// It makes:   projects.html              the list
//             project-<slug>.html        one page per project
// Paper details (title, authors, venue, contribution, links, picture) are read from
// publications.html by the paper's id, so a paper is only ever written in one place.
// The .html files are generated: edit projects.json or publications.html, never these pages.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const check = process.argv.includes('--check');
const page = readFileSync('projects/_page.html', 'utf8').replace(/^<!--.*-->\n/, '');
const projects = JSON.parse(readFileSync('projects/projects.json', 'utf8'));
const pubs = readFileSync('publications.html', 'utf8');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const plain = (s) => s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&#39;|&rsquo;/g, '’').replace(/\s+/g, ' ').trim();
const GENERATED = '<!-- Generated by scripts/build-projects.mjs from projects/projects.json and publications.html. Edit those, not this file. -->\n';

/* ---------- read one paper out of publications.html ---------- */
function paper(id) {
  const m = pubs.match(new RegExp(`<article class="pub" id="${id}">([\\s\\S]*?)</article>`));
  if (!m) throw new Error(`projects.json names paper "${id}", but publications.html has no <article class="pub" id="${id}">`);
  const a = m[1];
  const pick = (re) => { const x = a.match(re); return x ? x[1].replace(/\s+/g, ' ').trim() : ''; };
  const img = a.match(/<img\b[^>]*>/);
  const attr = (tag, name) => { const x = tag && tag.match(new RegExp(`\\s${name}="([^"]*)"`)); return x ? x[1] : ''; };
  const title = a.match(/<h3>\s*<a[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/);
  const links = [...(pick(/<div class="pub-actions">([\s\S]*?)<\/div>/) || '').matchAll(/<a[^>]*href="([^"]+)"[^>]*>([^<]+)<\/a>/g)]
    .map((l) => ({ href: l[1], label: l[2].trim() }));
  return {
    id,
    img: img ? { src: attr(img[0], 'src'), alt: attr(img[0], 'alt'), w: attr(img[0], 'width'), h: attr(img[0], 'height') } : null,
    venueTag: pick(/<span class="venue-tag">([^<]+)</),
    award: pick(/<span class="award">([^<]+)</),
    href: title ? title[1] : '', title: title ? title[2].replace(/\s+/g, ' ').trim() : '',
    authors: pick(/<p class="pub-authors">([\s\S]*?)<\/p>/),
    venue: pick(/<p class="pub-venue">([\s\S]*?)<\/p>/),
    blurb: pick(/<span class="contribution-label">[^<]*<\/span>([\s\S]*?)<\/p>/),
    year: (pick(/<span class="venue-tag">([^<]+)</).match(/\d{4}/) || [''])[0],
    links,
  };
}

/* ---------- a small pencil sketch for a project that has no photo yet ---------- */
function robotSketch() {
  let seed = 41;
  const r = () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
  const j = (a) => (r() - 0.5) * 2 * a, f = (n) => Math.round(n * 10) / 10;
  const st = (x1, y1, x2, y2, a = 1) => {
    const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1, bow = j(a);
    return `M${f(x1 + j(a * .6))} ${f(y1 + j(a * .6))}Q${f((x1 + x2) / 2 - dy / len * bow)} ${f((y1 + y2) / 2 + dx / len * bow)} ${f(x2 + j(a * .6))} ${f(y2 + j(a * .6))}`;
  };
  const L = (x1, y1, x2, y2, a = 1) => st(x1, y1, x2, y2, a) + st(x1, y1, x2, y2, a);
  const E = (cx, cy, rx, ry, a = .8) => { let d = ''; const s0 = r() * 6.28; for (let i = 0; i <= 24; i++) { const t = s0 + i / 22 * 6.283; d += (i ? 'L' : 'M') + f(cx + Math.cos(t) * (rx + j(a))) + ' ' + f(cy + Math.sin(t) * (ry + j(a))); } return d; };
  const R = (x, y, w, h, a = 1) => L(x - 2, y, x + w + 2, y, a) + L(x + w, y - 2, x + w, y + h + 2, a) + L(x + w + 2, y + h, x - 2, y + h, a) + L(x, y + h + 2, x, y - 2, a);
  const P = (d, c = 'pj-ink') => `<path class="${c}" d="${d}"/>`;
  let h = '';
  // pavement: ground line, joints, kerb and a strip of tactile paving
  h += P(L(20, 250, 700, 250, 1.4)) + P(L(20, 262, 700, 262, 1), 'pj-ink soft');
  for (let x = 70; x < 700; x += 105) h += P(st(x, 250, x - 14, 262, .6), 'pj-ink soft');
  h += `<rect class="pj-wash yellow" x="500" y="240" width="134" height="9"/>`;
  let dots = ''; for (let x = 508; x < 630; x += 12) dots += E(x, 244.5, 1.6, 1.3, .2);
  h += P(dots, 'pj-ink soft');
  // street tree and a utility pole, as on a Tokyo street
  let crown = ''; for (let i = 0; i < 9; i++) { const a = i / 9 * 6.283; crown += E(96 + Math.cos(a) * 30, 96 + Math.sin(a) * 26, 17, 15, 1); }
  h += `<ellipse class="pj-wash green" cx="100" cy="100" rx="46" ry="40"/>` + P(crown, 'pj-ink soft') + P(L(94, 138, 92, 250, 1) + L(102, 138, 104, 250, 1));
  h += P(L(660, 30, 660, 250, .8) + st(642, 52, 678, 52, .5) + st(646, 66, 674, 66, .5)) + P(`M660 52Q520 84 380 40M660 66Q520 98 380 56`, 'pj-ink soft');
  // a person walking (bag on the shoulder)
  const px = 300;
  h += `<ellipse class="pj-wash blue" cx="${px + 3}" cy="150" rx="19" ry="38"/>`;
  h += P(E(px, 84, 15, 16, .7)) + P(L(px, 100, px - 2, 176, 1) + st(px - 2, 176, px - 22, 250, 1) + st(px - 2, 176, px + 20, 250, 1) + st(px - 22, 250, px - 34, 250, .5) + st(px + 20, 250, px + 32, 250, .5) +
       st(px, 118, px - 24, 158, .9) + st(px, 118, px + 22, 152, .9) + st(px + 22, 152, px + 34, 140, .7));
  h += P(R(px - 40, 152, 20, 24, .7) + st(px - 30, 152, px - 4, 112, .5), 'pj-ink soft');
  h += P(st(px - 5, 82, px - 4, 83, .2) + st(px + 6, 82, px + 7, 83, .2) + st(px - 3, 91, px + 5, 91, .6));
  // the co-walker robot: wheeled body, mast, round head with a face, a small arrow light
  const rx = 440;
  h += `<path class="pj-wash orange" d="M${rx - 30} 172H${rx + 38}V236H${rx - 30}Z"/>`;
  h += P(R(rx - 34, 168, 68, 66, 1.1)) + P(L(rx - 26, 186, rx + 26, 186, .6) + R(rx - 12, 198, 24, 18, .6), 'pj-ink soft');
  h += P(E(rx - 20, 240, 10, 10, .6) + E(rx - 20, 240, 3.5, 3.5, .3) + E(rx + 20, 240, 10, 10, .6) + E(rx + 20, 240, 3.5, 3.5, .3));
  h += P(L(rx - 4, 168, rx - 4, 132, .7) + L(rx + 4, 168, rx + 4, 132, .7));
  h += `<ellipse class="pj-paper" cx="${rx}" cy="112" rx="26" ry="21"/>` + P(E(rx, 112, 26, 21, .8));
  h += P(E(rx - 9, 109, 2.6, 3.4, .2) + E(rx + 9, 109, 2.6, 3.4, .2) + `M${rx - 8} 119Q${rx} 126 ${rx + 8} 119`);
  h += P(st(rx, 91, rx, 80, .4) + E(rx, 77, 3, 3, .3), 'pj-ink soft');
  // what it tells people: a soft light on the ground and an arrow, "after you"
  h += `<ellipse class="pj-wash teal" cx="${rx + 92}" cy="256" rx="46" ry="7"/>`;
  h += P(`M${rx + 50} 214Q${rx + 84} 196 ${rx + 122} 214` + st(rx + 122, 214, rx + 110, 206, .5) + st(rx + 122, 214, rx + 108, 219, .5), 'pj-ink accent');
  h += P(`M${rx - 44} 96Q${rx - 58} 112 ${rx - 46} 128M${rx - 56} 88Q${rx - 76} 112 ${rx - 58} 136`, 'pj-ink soft');
  return `<svg class="pj-sketch" viewBox="0 18 720 256" role="img" aria-label="Pencil sketch: a person walking on a sidewalk with a small wheeled robot beside them, signalling which way it will go">${h}</svg>`;
}
const SKETCHES = { robot: robotSketch };

/* ---------- pieces ---------- */
function resolve(p) {
  const steps = (p.steps || []).map((s) => ({ ...paper(s.id), stage: s.stage || '' }));
  const lead = p.fromPaper ? paper(p.fromPaper) : null;
  return {
    ...p, steps,
    summary: p.summary || (lead ? lead.blurb : ''),
    imageAlt: p.imageAlt || (lead && lead.img ? lead.img.alt : ''),
    file: `project-${p.slug}.html`,
  };
}
const tags = (p) => `<ul class="pj-tags" aria-label="Topics">${p.tags.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>`;
function picture(p, eager) {
  if (p.sketch) return SKETCHES[p.sketch]();
  const src = p.image, lead = p.steps.find((s) => s.img && s.img.src === src);
  const size = lead ? ` width="${lead.img.w}" height="${lead.img.h}"` : '';
  return `<img${size} ${eager ? 'fetchpriority="high"' : 'loading="lazy"'} decoding="async" src="${src}" alt="${esc(p.imageAlt)}" />`;
}
function paperCard(s, n) {
  const links = s.links.map((l) => `<a href="${l.href}" target="_blank" rel="noopener">${esc(l.label)}</a>`).join('');
  return `          <li class="pj-step">
            <div class="pj-when"><span class="pj-year">${s.year}</span>${s.stage ? `<span class="pj-stage">${esc(s.stage)}</span>` : ''}</div>
            <div class="pj-paper">
              <p class="pj-venue">${esc(s.venueTag)}${s.award ? ` <span class="pj-award">${s.award}</span>` : ''}</p>
              <h3><a href="${s.href}" target="_blank" rel="noopener">${s.title}</a></h3>
              <p class="pj-blurb">${s.blurb}</p>
              <p class="pj-authors">${s.authors}</p>
              <p class="pj-links">${links}<a href="publications.html#${s.id}">Citation</a></p>
            </div>${s.img ? `
            <a class="pj-thumb" href="${s.href}" target="_blank" rel="noopener" tabindex="-1" aria-hidden="true"><img width="${s.img.w}" height="${s.img.h}" loading="lazy" decoding="async" src="${s.img.src}" alt="" /></a>` : ''}
          </li>`;
}
function people(p) {
  const seen = new Map();
  for (const s of p.steps) for (const raw of plain(s.authors).split(',')) {
    const name = raw.trim(); if (!name || name === 'Vishal Chauhan') continue;
    seen.set(name, (seen.get(name) || 0) + 1);
  }
  return [...seen].sort((a, b) => b[1] - a[1]).map((x) => x[0]);
}

function projectPage(p, all) {
  const others = all.filter((o) => o.slug !== p.slug);
  const who = people(p);
  const body = `    <article class="pj">
      <div class="container">
        <p class="pj-back"><a href="projects.html">← Projects</a></p>
        ${tags(p)}
        <h1 class="page-title">${esc(p.title)}</h1>
        ${p.subtitle ? `<p class="pj-sub">${esc(p.subtitle)}</p>` : ''}
        <p class="pj-years">${esc(p.years)}</p>

        <figure class="pj-hero${p.sketch ? ' is-sketch' : ''}">${picture(p, true)}</figure>

        <div class="pj-lead">
          <p class="pj-summary">${p.summary}</p>
          <dl class="pj-facts">${p.facts.map((f) => `<div><dt>${esc(f[0])}</dt><dd>${f[1]}</dd></div>`).join('')}</dl>
        </div>
        ${p.links.length ? `<p class="pj-actions">${p.links.map((l) => `<a href="${l.href}"${/^https?:/.test(l.href) ? ' target="_blank" rel="noopener"' : ''}>${esc(l.label)}</a>`).join('')}</p>` : ''}
${p.steps.length ? `
        <h2 class="pj-h2">${esc(p.papersTitle || 'Publications')}</h2>
        <ol class="pj-steps${p.steps.length > 1 ? ' is-timeline' : ''}">
${p.steps.map(paperCard).join('\n')}
        </ol>` : `
        <p class="pj-soon">Started in 2026. Papers and field results will be added here as they are published.</p>`}
${p.gallery ? `
        <h2 class="pj-h2">${esc(p.galleryTitle || 'Gallery')}</h2>
        <div class="pj-gallery">${p.gallery.map((g) => `
          <figure><img width="${g.w}" height="${g.h}" loading="lazy" decoding="async" src="${g.src}" alt="${esc(g.caption)}" /><figcaption>${esc(g.caption)}</figcaption></figure>`).join('')}
        </div>` : ''}
${who.length ? `
        <h2 class="pj-h2">With</h2>
        <p class="pj-people">${who.map(esc).join(' · ')}</p>` : ''}

        <h2 class="pj-h2">Other projects</h2>
        <ul class="pj-more">${others.map((o) => `<li><a href="${o.file}">${esc(o.title)}</a> <span>${esc(o.years)}</span></li>`).join('')}</ul>
        <p class="see-all"><a href="projects.html">← All projects</a></p>
      </div>
    </article>`;
  return fill({ title: p.title, description: plain(p.summary).slice(0, 180), image: p.image || 'photo.jpg', file: p.file, body });
}

function listPage(all) {
  const cards = all.map((p, i) => `          <li class="pj-card">
            <a class="pj-card-pic${p.sketch ? ' is-sketch' : ''}" href="${p.file}" tabindex="-1" aria-hidden="true">${picture(p, i === 0).replace(/alt="[^"]*"/, 'alt=""')}</a>
            <div class="pj-card-body">
              <p class="pj-venue">Research project · ${esc(p.years)}</p>
              <h2><a href="${p.file}">${esc(p.title)}</a></h2>
              <p class="pj-blurb">${p.summary}</p>
              ${tags(p)}
              <p class="pj-count">${p.steps.length ? `${p.steps.length} paper${p.steps.length > 1 ? 's' : ''}` : 'in progress'}</p>
            </div>
          </li>`).join('\n');
  const body = `    <section>
      <div class="container">
        <p class="section-eyebrow">Research</p>
        <h1 class="page-title">Projects.</h1>
        <ul class="pj-list">
${cards}
        </ul>
        <p class="see-all"><a href="index.html">← Back to home</a></p>
      </div>
    </section>`;
  return fill({ title: 'Projects', description: 'Research projects by Vishal Chauhan: ' + all.map((p) => p.title).join(', ') + '.', image: 'photo.jpg', file: 'projects.html', body });
}

function fill(v) {
  return GENERATED + page.replace(/\{\{(\w+)\}\}/g, (m, k) => (k === 'body' ? v.body : esc(v[k])));
}

/* ---------- build ---------- */
const all = projects.map(resolve);
const out = { 'projects.html': listPage(all) };
for (const p of all) out[p.file] = projectPage(p, all);

let stale = 0;
for (const [file, html] of Object.entries(out)) {
  const now = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (now === html) continue;
  stale++;
  if (check) console.log(`✗ ${file} is out of date. Run: node scripts/build-projects.mjs`);
  else writeFileSync(file, html);
}
if (check) { if (stale) process.exit(1); console.log('✓ Project pages are up to date.'); }
else console.log(stale ? `✓ Built ${stale} project page(s).` : '✓ Project pages already up to date.');
